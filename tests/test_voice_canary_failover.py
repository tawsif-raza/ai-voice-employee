"""
Claude -> Gemini Failover Canary Test Suite (tests/test_voice_canary_failover.py)

Validates Criterion 4:
- Claude rate-limit / quota failure (HTTP 429) triggers automatic Gemini fallback
- Conversation seamlessly continues without dropped calls
- Audio output is successfully generated by Gemini and transmitted to caller
- No duplicate tool executions or duplicate user-facing turns
- Audit logging records failover event with primary and fallback metadata
- Metrics counter `llm_failover_events_total` is incremented
- Cooldown window routes subsequent turns directly to fallback
"""

