DEFAULT_BENCHMARK_PATH = Path(__file__).resolve().parent / "benchmark_200.json"


def _case_to_turns(case: dict) -> list[dict]:
    """Normalize a case to its list of turn dicts, whether it's the new {turns: [...]} shape or a legacy single-{message} case (CORE_BENCHMARK)."""
    if "turns" in case:
        return case["turns"]
    return [
        {
            "message": case["message"],
            "expected_handoff": case["expected_handoff"],
            "expected_chunk_id": case.get("expected_chunk_id"),
            "expected_clinical_guard": case.get("expected_clinical_guard", False),
        }
    ]


def load_benchmark(quick: bool, benchmark_path: Optional[str], sample: Optional[int]) -> list[dict]:
    if quick:
        return CORE_BENCHMARK

    path = Path(benchmark_path) if benchmark_path else DEFAULT_BENCHMARK_PATH
    if not path.exists():
        print(
            f"WARNING: {path} not found — falling back to the 20-case CORE_BENCHMARK. "
            f"Run `python src/eval/generate_benchmark.py` to create the full 200-case set."
        )
        return CORE_BENCHMARK

    with open(path, "r", encoding="utf-8") as f:
        cases = json.load(f)

    if sample and sample < len(cases):
        cases = random.Random(42).sample(cases, sample)

    return cases


# ── Per-turn / per-case evaluation ──────────────────────────────────────────


def run_turn(assistant: VoiceAssistantInference, turn: dict, history: list[dict]) -> dict:
    """Run one conversational turn (with accumulated history) and score it against its expectations."""
    start = time.perf_counter()
    ttft_ms = None
    final = None

    for item in assistant.generate_response_stream(turn["message"], history=history):
        if isinstance(item, str):
            if ttft_ms is None:
                ttft_ms = (time.perf_counter() - start) * 1000
        else:
            final = item

    response_text = final["response"]
    word_count = len(response_text.split())
    token_count = len(assistant.tokenizer.encode(response_text)) if response_text else 0
    latency_ms = final["latency_ms"]
    throughput = token_count / (latency_ms / 1000) if latency_ms > 0 and token_count else 0.0
    predicted_handoff = final["is_handoff"]

    retrieved_chunks = final.get("retrieved_chunks", [])
    retrieved_ids = [c["id"] for c in retrieved_chunks]
    expected_chunk_id = turn.get("expected_chunk_id")
    retrieval_hit = (expected_chunk_id in retrieved_ids) if expected_chunk_id else None

    return {
        "message": turn["message"],
        "expected_handoff": turn["expected_handoff"],
        "expected_chunk_id": expected_chunk_id,
        "expected_clinical_guard": turn.get("expected_clinical_guard", False),
        "response": response_text,
        "predicted_handoff": predicted_handoff,
        "predicted_handoff_confidence": final.get("handoff_confidence"),
        "clinical_guard_triggered": final.get("clinical_guard_triggered", False),
        "correct_handoff": predicted_handoff == turn["expected_handoff"],
        "retrieved_chunk_ids": retrieved_ids,
        "retrieval_hit": retrieval_hit,
        "word_count": word_count,
        "token_count": token_count,
        "ttft_ms": ttft_ms if ttft_ms is not None else latency_ms,
        "latency_ms": latency_ms,
        "throughput_tok_s": throughput,
    }


def run_case(assistant: VoiceAssistantInference, case: dict) -> dict:
    """
    Run one benchmark case — single- or multi-turn — accumulating
    conversation history turn over turn, and return a conversation-level
    record: case metadata plus the list of per-turn results.
    """
    history: list[dict] = []
    turn_results = []
    for turn in _case_to_turns(case):
        result = run_turn(assistant, turn, history)
        turn_results.append(result)
        history.append({"role": "user", "content": turn["message"]})
        history.append({"role": "assistant", "content": result["response"]})

    return {
        "id": case["id"],
        "category": case["category"],
        "turns": turn_results,
        "all_turns_correct_handoff": all(t["correct_handoff"] for t in turn_results),
    }


# ── Aggregation ──────────────────────────────────────────────────────────────


def _percentile(values: list[float], pct: float) -> float:
    """Linear-interpolation percentile, dependency-free (no numpy)."""
    if not values:
        return 0.0
    sorted_vals = sorted(values)
    k = (len(sorted_vals) - 1) * (pct / 100)
    f, c = int(k), min(int(k) + 1, len(sorted_vals) - 1)
    if f == c:
        return sorted_vals[f]
    return sorted_vals[f] + (sorted_vals[c] - sorted_vals[f]) * (k - f)


def _flatten_turns(results: list[dict]) -> list[tuple[str, dict]]:
    """[(category, turn_result), ...] across every case."""
    return [(r["category"], t) for r in results for t in r["turns"]]


def compute_metrics(results: list[dict]) -> dict:
    flat = _flatten_turns(results)
    turns = [t for _, t in flat]

    word_counts = [t["word_count"] for t in turns]
    token_counts = [t["token_count"] for t in turns]
    ttfts = [t["ttft_ms"] for t in turns]
    latencies = [t["latency_ms"] for t in turns]
    throughputs = [t["throughput_tok_s"] for t in turns if t["throughput_tok_s"] > 0]

    tp = sum(1 for t in turns if t["predicted_handoff"] and t["expected_handoff"])
    fp = sum(1 for t in turns if t["predicted_handoff"] and not t["expected_handoff"])
    fn = sum(1 for t in turns if not t["predicted_handoff"] and t["expected_handoff"])
    tn = sum(1 for t in turns if not t["predicted_handoff"] and not t["expected_handoff"])

    retrieval_turns = [t for t in turns if t["retrieval_hit"] is not None]
    clinical_turns = [t for t in turns if t["expected_clinical_guard"]]

    return {
        "num_cases": len(results),
        "num_turns": len(turns),
        "accuracy": sum(1 for t in turns if t["correct_handoff"]) / len(turns) if turns else 0.0,
        "conversation_accuracy": (
            sum(1 for r in results if r["all_turns_correct_handoff"]) / len(results) if results else 0.0
        ),
        "avg_word_count": statistics.mean(word_counts) if word_counts else 0.0,
        "avg_token_count": statistics.mean(token_counts) if token_counts else 0.0,
        "avg_ttft_ms": statistics.mean(ttfts) if ttfts else 0.0,
        "avg_throughput_tok_s": statistics.mean(throughputs) if throughputs else 0.0,
        "latency_ms_avg": statistics.mean(latencies) if latencies else 0.0,
        "latency_ms_p50": _percentile(latencies, 50),
        "latency_ms_p90": _percentile(latencies, 90),
        "latency_ms_p99": _percentile(latencies, 99),
        "handoff_precision": tp / (tp + fp) if (tp + fp) else 0.0,
        "handoff_recall": tp / (tp + fn) if (tp + fn) else 0.0,
        "handoff_tp": tp,
        "handoff_fp": fp,
        "handoff_fn": fn,
        "handoff_tn": tn,
        "retrieval_hit_rate": (
            sum(1 for t in retrieval_turns if t["retrieval_hit"]) / len(retrieval_turns) if retrieval_turns else None
        ),
        "retrieval_evaluated_turns": len(retrieval_turns),
        "clinical_guard_accuracy": (
            sum(1 for t in clinical_turns if t["clinical_guard_triggered"]) / len(clinical_turns)
            if clinical_turns
            else None
        ),
        "clinical_evaluated_turns": len(clinical_turns),
        "by_category": _category_breakdown(flat),
    }


def _category_breakdown(flat: list[tuple[str, dict]]) -> dict:
    buckets: dict[str, dict] = {}
    for category, t in flat:
        b = buckets.setdefault(category, {"num_turns": 0, "correct": 0, "retrieval_eval": 0, "retrieval_hits": 0})
        b["num_turns"] += 1
        b["correct"] += 1 if t["correct_handoff"] else 0
        if t["retrieval_hit"] is not None:
            b["retrieval_eval"] += 1
            b["retrieval_hits"] += 1 if t["retrieval_hit"] else 0

    summary = {}
    for category, b in buckets.items():
        summary[category] = {
            "num_turns": b["num_turns"],
            "handoff_accuracy": b["correct"] / b["num_turns"] if b["num_turns"] else 0.0,
            "retrieval_hit_rate": (b["retrieval_hits"] / b["retrieval_eval"]) if b["retrieval_eval"] else None,
        }
    return summary


# ── Reporting ────────────────────────────────────────────────────────────────


def _turn_rows(results: list[dict]) -> list[tuple]:
    rows = []
    for r in results:
        for turn_idx, t in enumerate(r["turns"], start=1):
            label = f"{r['id']}" if len(r["turns"]) == 1 else f"{r['id']}.{turn_idx}"
            rows.append((label, r["category"], t))
    return rows


def print_summary_rich(results: list[dict], metrics: dict) -> None:
    console = Console()

    table = Table(title="Evaluation Results", show_lines=False)
    table.add_column("#", justify="right")
    table.add_column("Category")
    table.add_column("Handoff (exp/pred)")
    table.add_column("Retrieval")
    table.add_column("Words", justify="right")
    table.add_column("Latency ms", justify="right")

    for label, category, t in _turn_rows(results):
        mark = "[green]OK[/green]" if t["correct_handoff"] else "[red]MISS[/red]"
        if t["retrieval_hit"] is None:
            retrieval = "-"
        else:
            retrieval = "[green]hit[/green]" if t["retrieval_hit"] else "[red]miss[/red]"
        table.add_row(
            label,
            category,
            f"{t['expected_handoff']}/{t['predicted_handoff']} {mark}",
            retrieval,
            str(t["word_count"]),
            f"{t['latency_ms']:.0f}",
        )
    console.print(table)

    cat_table = Table(title="By Category", show_header=True)
    cat_table.add_column("Category")
    cat_table.add_column("Turns", justify="right")
    cat_table.add_column("Handoff acc.", justify="right")
    cat_table.add_column("Retrieval hit rate", justify="right")
    for category, stats in sorted(metrics["by_category"].items()):
        retrieval_str = f"{stats['retrieval_hit_rate']:.1%}" if stats["retrieval_hit_rate"] is not None else "-"
        cat_table.add_row(category, str(stats["num_turns"]), f"{stats['handoff_accuracy']:.1%}", retrieval_str)
    console.print(cat_table)

    summary = Table(title="Summary Metrics", show_header=False)
    summary.add_column("Metric")
    summary.add_column("Value", justify="right")
    summary.add_row("Cases / turns", f"{metrics['num_cases']} / {metrics['num_turns']}")
    summary.add_row("Handoff accuracy (per turn)", f"{metrics['accuracy']:.1%}")
    summary.add_row("Handoff accuracy (per conversation)", f"{metrics['conversation_accuracy']:.1%}")
    summary.add_row("Handoff precision", f"{metrics['handoff_precision']:.2f}")
    summary.add_row("Handoff recall", f"{metrics['handoff_recall']:.2f}")
    if metrics["retrieval_hit_rate"] is not None:
        summary.add_row(
            "Retrieval hit rate", f"{metrics['retrieval_hit_rate']:.1%} ({metrics['retrieval_evaluated_turns']} turns)"
        )
    if metrics["clinical_guard_accuracy"] is not None:
        summary.add_row(
            "Clinical guard accuracy",
            f"{metrics['clinical_guard_accuracy']:.1%} ({metrics['clinical_evaluated_turns']} turns)",
        )
    summary.add_row("Avg word count", f"{metrics['avg_word_count']:.1f}")
    summary.add_row("Avg token count", f"{metrics['avg_token_count']:.1f}")
    summary.add_row("Avg TTFT (ms)", f"{metrics['avg_ttft_ms']:.0f}")
    summary.add_row("Avg throughput (tok/s)", f"{metrics['avg_throughput_tok_s']:.2f}")
    summary.add_row(
        "Latency avg / p50 / p90 / p99 (ms)",
        f"{metrics['latency_ms_avg']:.0f} / {metrics['latency_ms_p50']:.0f} / "
        f"{metrics['latency_ms_p90']:.0f} / {metrics['latency_ms_p99']:.0f}",
    )
    console.print(summary)


def print_summary_plain(results: list[dict], metrics: dict) -> None:
    print("\n" + "=" * 90)
    print(f"{'#':>7} {'CATEGORY':<14} {'EXP/PRED':<14} {'OK':<5} {'RETR':<5} {'WORDS':>6} {'LAT ms':>8}")
    print("-" * 90)
    for label, category, t in _turn_rows(results):
        ok = "OK" if t["correct_handoff"] else "MISS"
        if t["retrieval_hit"] is None:
            retr = "-"
        else:
            retr = "hit" if t["retrieval_hit"] else "miss"
        exp_pred = f"{t['expected_handoff']}/{t['predicted_handoff']}"
        print(
            f"{label:>7} {category:<14} {exp_pred:<14} {ok:<5} {retr:<5} {t['word_count']:>6} {t['latency_ms']:>8.0f}"
        )
    print("=" * 90)
    print("By category:")
    for category, stats in sorted(metrics["by_category"].items()):
        retrieval_str = (
            f", retrieval hit rate {stats['retrieval_hit_rate']:.1%}" if stats["retrieval_hit_rate"] is not None else ""
        )
        print(
            f"  {category:<14} turns={stats['num_turns']:<4} handoff_acc={stats['handoff_accuracy']:.1%}{retrieval_str}"
        )
    print("=" * 90)
    print(f"Cases / turns                     : {metrics['num_cases']} / {metrics['num_turns']}")
    print(f"Handoff accuracy (per turn)       : {metrics['accuracy']:.1%}")
    print(f"Handoff accuracy (per conversation): {metrics['conversation_accuracy']:.1%}")
    print(f"Handoff precision                 : {metrics['handoff_precision']:.2f}")
    print(f"Handoff recall                    : {metrics['handoff_recall']:.2f}")
    if metrics["retrieval_hit_rate"] is not None:
        print(
            f"Retrieval hit rate                 : {metrics['retrieval_hit_rate']:.1%} ({metrics['retrieval_evaluated_turns']} turns)"
        )
    if metrics["clinical_guard_accuracy"] is not None:
        print(
            f"Clinical guard accuracy            : {metrics['clinical_guard_accuracy']:.1%} ({metrics['clinical_evaluated_turns']} turns)"
        )
    print(f"Avg word count                     : {metrics['avg_word_count']:.1f}")
    print(f"Avg token count                    : {metrics['avg_token_count']:.1f}")
    print(f"Avg TTFT (ms)                       : {metrics['avg_ttft_ms']:.0f}")
    print(f"Avg throughput (tok/s)              : {metrics['avg_throughput_tok_s']:.2f}")
    print(
        f"Latency avg/p50/p90/p99 (ms)        : {metrics['latency_ms_avg']:.0f} / {metrics['latency_ms_p50']:.0f} / "
        f"{metrics['latency_ms_p90']:.0f} / {metrics['latency_ms_p99']:.0f}"
    )
    print("=" * 90 + "\n")


def print_summary(results: list[dict], metrics: dict) -> None:
    if _HAS_RICH:
        print_summary_rich(results, metrics)
    else:
        print_summary_plain(results, metrics)


# ── Entry point ────────────────────────────────────────────────────────────────


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate the voice assistant against the benchmark")
    parser.add_argument("--base_model", default="Qwen/Qwen2.5-0.5B-Instruct")
    parser.add_argument(
        "--adapter_path",
        default=None,
        help="LoRA checkpoint directory. Auto-resolved from outputs/checkpoint-final "
        "or the latest outputs/checkpoint-* if omitted.",
    )
    parser.add_argument("--max_new_tokens", type=int, default=150)
    parser.add_argument(
        "--quick",
        action="store_true",
        help="Run only the 20-case hand-curated CORE_BENCHMARK (fast smoke test) instead of the full 200-case benchmark.",
    )
    parser.add_argument(
        "--benchmark",
        default=None,
        help=f"Path to a benchmark JSON file (default: {DEFAULT_BENCHMARK_PATH.name}, generated by generate_benchmark.py). Ignored with --quick.",
    )
    parser.add_argument(
        "--sample",
        type=int,
        default=None,
        help="Run a reproducible random subset of N cases from the loaded benchmark instead of all of them (fixed seed=42). Ignored with --quick.",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Defaults to outputs/evaluation/eval_results_200.json (full run) or the configured evaluation.results_path (--quick).",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    benchmark = load_benchmark(quick=args.quick, benchmark_path=args.benchmark, sample=args.sample)

    print("=" * 60)
    print("QWEN 2.5 VOICE ASSISTANT — EVALUATION")
    print("=" * 60)
    mode = "CORE (quick)" if args.quick else ("full" if not args.sample else f"sample of {len(benchmark)}")
    print(f"Benchmark cases: {len(benchmark)} [{mode}]")

    assistant = VoiceAssistantInference(
        base_model_name=args.base_model,
        adapter_path=args.adapter_path,
        max_new_tokens=args.max_new_tokens,
        temperature=0.0,  # deterministic (greedy) so re-runs are comparable
    )

    results = []
    for i, case in enumerate(benchmark, start=1):
        turns = _case_to_turns(case)
        preview = turns[0]["message"][:50]
        suffix = f" (+{len(turns) - 1} more turn{'s' if len(turns) > 2 else ''})" if len(turns) > 1 else ""
        print(f"[{i}/{len(benchmark)}] id={case['id']} {case['category']}: {preview}{suffix}")
        results.append(run_case(assistant, case))

    metrics = compute_metrics(results)
    print_summary(results, metrics)

    if args.output:
        output_path = Path(args.output)
    elif args.quick:
        output_path = Path(_get("results_path", "outputs/eval_results.json"))
    else:
        output_path = Path("outputs/evaluation/eval_results_200.json")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump({"metrics": metrics, "results": results}, f, indent=2)
    print(f"Saved detailed results to {output_path}")
